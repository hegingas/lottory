export const meta = {
  name: 'pl5-funnel-pick',
  description: '排列5三层漏斗+对抗验证+自辩：按位结构→跨位形态→精选→4人审查→漏斗自辩→终裁(深冻>0.99安全)',
  phases: [{title:'数据准备'},{title:'三层漏斗'},{title:'对抗验证'},{title:'漏斗自辩'},{title:'终裁'}],
};

